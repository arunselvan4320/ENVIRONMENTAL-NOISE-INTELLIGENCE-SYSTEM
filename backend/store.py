def database_url():
    value = os.getenv('DATABASE_URL') or os.getenv('KAANAM_DATABASE_URL')
    if not value:
        return ''
    value = value.strip()
    if value.startswith('postgres://'):
        value = 'postgresql://' + value[len('postgres://'):]
    return value


def using_postgres():
    return bool(database_url())


class Inserted:
    def __init__(self, row_id):
        self.lastrowid = row_id
        self.rowcount = 1

    def fetchone(self):
        return None

    def fetchall(self):
        return []


def adapt_sql(sql, postgres):
    if not postgres:
        return sql
    text = sql.strip().replace('?', '%s')
    upper = text.upper()
    if upper.startswith('INSERT OR IGNORE INTO SETTINGS'):
        return 'INSERT INTO settings(id) VALUES(1) ON CONFLICT (id) DO NOTHING'
    if upper.startswith('INSERT OR IGNORE INTO AI_EVENTS'):
        text = 'INSERT INTO ai_events' + text.split('ai_events', 1)[1]
        return text.rstrip().rstrip(';') + ' ON CONFLICT (observation_id) DO NOTHING'
    if upper.startswith('INSERT INTO OBSERVATIONS') and 'RETURNING' not in upper:
        return text.rstrip().rstrip(';') + ' RETURNING id'
    return text


class Connection:
    def __init__(self, raw, postgres):
        self.raw = raw
        self.postgres = postgres

    def execute(self, sql, args=()):
        statement = adapt_sql(sql, self.postgres)
        if self.postgres:
            cursor = self.raw.execute(statement, args or None)
            if statement.upper().rstrip().endswith('RETURNING ID'):
                row = cursor.fetchone()
                return Inserted(row['id'] if row else None)
            return cursor
        if args:
            return self.raw.execute(statement, args)
        return self.raw.execute(statement)

    def executescript(self, script):
        if self.postgres:
            raise RuntimeError('PostgreSQL schema is applied statement by statement.')
        self.raw.executescript(script)

    def commit(self):
        self.raw.commit()

    def rollback(self):
        self.raw.rollback()

    def close(self):
        self.raw.close()


def connect(sqlite_path):
    url = database_url()
    if url:
        import psycopg
        from psycopg.rows import dict_row
        raw = psycopg.connect(url, row_factory=dict_row, prepare_threshold=None)
        return Connection(raw, True)
    path = Path(sqlite_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    raw = sqlite3.connect(path, timeout=15)
    raw.row_factory = sqlite3.Row
    raw.execute('PRAGMA foreign_keys=ON')
    return Connection(raw, False)


@contextmanager
def db(sqlite_path):
    connection = connect(sqlite_path)
    try:
        yield connection
        connection.commit()
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


def init_schema(sqlite_path):
    with db(sqlite_path) as connection:
        if connection.postgres:
            for statement in POSTGRES_SCHEMA:
                connection.execute(statement)
        else:
            connection.executescript(SQLITE_SCHEMA)


def is_duplicate(error):
    return type(error).__name__ in {'IntegrityError', 'UniqueViolation'}
